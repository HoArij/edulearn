/* ===== Moteur de traduction ===== */
const I18N = {
  lang: localStorage.getItem("lms-lang") || "fr",

  t(key) {
    return (UI[I18N.lang] && UI[I18N.lang][key]) || UI.fr[key] || key;
  },

  /* Choisit la bonne langue dans un objet {fr, en, ar} (repli sur le français) */
  pick(obj) {
    if (!obj) return "";
    if (typeof obj === "string") return obj;
    return obj[I18N.lang] || obj.fr || "";
  },

  set(lang) {
    I18N.lang = lang;
    localStorage.setItem("lms-lang", lang);
    I18N.setDir();
  },

  setDir() {
    document.documentElement.lang = I18N.lang;
    document.documentElement.dir = I18N.lang === "ar" ? "rtl" : "ltr";
  },

  apply(root = document) {
    root.querySelectorAll("[data-i18n]").forEach(el => el.textContent = I18N.t(el.dataset.i18n));
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => el.placeholder = I18N.t(el.dataset.i18nPlaceholder));
    root.querySelectorAll("[data-i18n-aria]").forEach(el => el.setAttribute("aria-label", I18N.t(el.dataset.i18nAria)));
  }
};

I18N.setDir();